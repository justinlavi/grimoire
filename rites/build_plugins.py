#!/usr/bin/env python3
"""Render the framework's command families as Claude Code plugins under plugins/.

Claude Code installs the framework from the repository's own marketplace
(`.claude-plugin/marketplace.json`): one plugin per command family, `grimoire`
and `grimoire-dev`. Each plugin is a thin carrier: its skills are rendered from the same
`skills/<family>/<slug>/SKILL.md` sources the flat registration uses, with
every invocation inlined, so a plugin skill is self-contained and runs the
framework at its one location, `~/.grimoire`. A plugin's description comes from
its marketplace entry, which owns it.

Rendered files: `plugins/<plugin>/.claude-plugin/plugin.json` and
`skills/<slug>/SKILL.md` for every plugin, plus `scripts/grimoire_block.md` and
`bin/*` for the `grimoire` plugin, which carries the session-start hook. The
hook itself (`hooks/`) and the rest of `scripts/` are authored in place and are
never touched.

The rendered tree is committed: a marketplace serves it straight from git.

Mutation profile: plan_apply. The default mode writes nothing and reports the
drift between the sources and the committed render, and the test suite runs
that check. `--apply` writes the render and removes files it no longer
produces.

Usage:
    python rites/build_plugins.py [--apply] [--format human|json|jsonl]

Exit codes: 0 = in sync or written, 1 = drift found (without --apply),
2 = argparse invalid arguments.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Callable

import sync_skills
from _lib import read_utf8, warn, write_utf8
from diagnostics import ResultReporter, add_output_format_arg

FRAMEWORK_PATH = Path(__file__).resolve().parent.parent
PLUGINS_DIR = FRAMEWORK_PATH / "plugins"
MARKETPLACE = FRAMEWORK_PATH / ".claude-plugin" / "marketplace.json"
FRAMEWORK_HOME = "~/.grimoire"
GENERATED_COMMENT = (
    "<!-- GENERATED by rites/build_plugins.py from {source} - do not edit; "
    "edit the source and run <framework>/bin/grimoire build_plugins --apply -->"
)
SESSION_PLUGIN = "grimoire"
NAME_RE = re.compile(r"^name:\s*.*$", re.MULTILINE)


def plugin_descriptions() -> dict[str, str]:
    """Return {plugin name: description} from the marketplace, which owns the wording."""
    marketplace = json.loads(read_utf8(MARKETPLACE))
    return {entry["name"]: entry["description"] for entry in marketplace["plugins"]}


def plugin_command_names(
    text: str,
    families: list[dict] | None = None,
    specs: list[sync_skills.SkillSpec] | None = None,
) -> str:
    """Spell every framework command the way a plugin install types it.

    Flat registration names a command `/grm-add` or `/grm-dev-validate`; Claude
    Code names the same plugin skill `/grimoire:add` or `/grimoire-dev:validate`.
    `families` and `specs` default to the framework's own; `render_all` loads
    them once and passes them in.
    """
    if families is None:
        families = sync_skills.load_framework_skill_families()
    if specs is None:
        specs = sync_skills.collect_framework_skill_specs()
    plugin_of = {family["name"]: family["plugin"] for family in families}
    for spec in sorted(specs, key=lambda spec: -len(spec.command_name)):
        plugin_name = f"/{plugin_of[spec.source_key]}:{spec.source_dir.name}"
        text = re.sub(rf"(?<![\w/])/{re.escape(spec.command_name)}(?![\w-])", plugin_name, text)
    # Whatever still opens with a family stem (`/grm-*`, `/grm-...`), longest stem first.
    stems = sorted(
        ((f"{family['skill_prefix']}-{family['slug_prefix']}-" if family["slug_prefix"] else f"{family['skill_prefix']}-", family["plugin"])
         for family in families),
        key=lambda item: -len(item[0]),
    )
    for stem, plugin in stems:
        text = re.sub(rf"(?<![\w/])/{re.escape(stem)}", f"/{plugin}:", text)
    return text


def version() -> str:
    return read_utf8(FRAMEWORK_PATH / "VERSION").strip()


def render_plugin_skill(
    spec: sync_skills.SkillSpec,
    families: list[dict] | None = None,
    specs: list[sync_skills.SkillSpec] | None = None,
    on_warning: Callable[[str], None] = warn,
) -> str:
    """Render one source skill for the plugin: slug name, framework at its home path."""
    source = spec.source_dir / "SKILL.md"
    # Rendered against the real checkout so every directive inlines; the framework
    # home replaces the real path once the text is assembled.
    content = sync_skills.render_skill_body(spec, on_warning)
    content = content.replace(sync_skills.FRAMEWORK_PATH.as_posix(), FRAMEWORK_HOME)
    content = plugin_command_names(content, families, specs)
    # Claude Code names a plugin skill /<plugin>:<name>; the family prefix is
    # the plugin, so the skill keeps only its slug.
    content = NAME_RE.sub(f"name: {spec.source_dir.name}", content, count=1)
    comment = GENERATED_COMMENT.format(source=source.relative_to(FRAMEWORK_PATH).as_posix())
    return sync_skills.insert_after_frontmatter(content, comment)


def render_family(
    family: dict,
    families: list[dict],
    specs: list[sync_skills.SkillSpec],
    descriptions: dict[str, str],
    on_warning: Callable[[str], None] = warn,
) -> dict[str, str]:
    """Return {relative path: content} for one family's plugin tree."""
    files: dict[str, str] = {}
    # `version` is the release number in VERSION. Claude Code offers an update
    # when it differs from the installed one, so a release reaches installed
    # machines together with the framework checkout the session hook
    # fast-forwards.
    manifest = {
        "name": family["plugin"],
        "version": version(),
        "description": descriptions[family["plugin"]],
        "author": {"name": "Justin Lavi", "url": "https://github.com/justinlavi/grimoire"},
        "homepage": "https://github.com/justinlavi/grimoire",
        "repository": "https://github.com/justinlavi/grimoire",
        "license": "MIT",
    }
    files[".claude-plugin/plugin.json"] = json.dumps(manifest, indent=2) + "\n"
    for spec in specs:
        if spec.source_key == family["name"]:
            files[f"skills/{spec.source_dir.name}/SKILL.md"] = render_plugin_skill(spec, families, specs, on_warning)
    if family["plugin"] == SESSION_PLUGIN:
        # The hook prints the routing block before the framework exists, so the
        # plugin carries a copy of the canonical template; the launcher goes on
        # the agent's PATH through the plugin's bin/.
        files["scripts/grimoire_block.md"] = read_utf8(FRAMEWORK_PATH / "rites" / "templates" / "grimoire_block.md")
        for name in ("grimoire", "grimoire.cmd", "grimoire.py"):
            files[f"bin/{name}"] = read_utf8(FRAMEWORK_PATH / "bin" / name)
    return files


def render_all(on_warning: Callable[[str], None] = warn) -> dict[str, str]:
    """Return {path relative to plugins/: content} for every family."""
    families = sync_skills.load_framework_skill_families(on_warning)
    specs = sync_skills.collect_framework_skill_specs(on_warning)
    descriptions = plugin_descriptions()
    rendered: dict[str, str] = {}
    for family in families:
        for rel, content in render_family(family, families, specs, descriptions, on_warning).items():
            rendered[f"{family['plugin']}/{rel}"] = content
    return rendered


def current_render_targets() -> dict[str, str]:
    """The committed files this rite owns: plugin.json, skills, bin and the routing block copy."""
    existing: dict[str, str] = {}
    if not PLUGINS_DIR.is_dir():
        return existing
    for path in sorted(PLUGINS_DIR.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(PLUGINS_DIR).as_posix()
        parts = rel.split("/")
        if (len(parts) >= 2 and parts[1] in {"skills", ".claude-plugin", "bin"}) or rel.endswith("/scripts/grimoire_block.md"):
            existing[rel] = read_utf8(path)
    return existing


def diff(rendered: dict[str, str], existing: dict[str, str]) -> dict[str, list[str]]:
    return {
        "create": sorted(set(rendered) - set(existing)),
        "update": sorted(k for k in rendered if k in existing and existing[k] != rendered[k]),
        "remove": sorted(set(existing) - set(rendered)),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Render the framework's command families as Claude Code plugins")
    parser.add_argument("--apply", action="store_true", help="Write the rendered plugin tree (default: report drift)")
    add_output_format_arg(parser)
    args = parser.parse_args()
    human = args.format == "human"

    reporter = ResultReporter("build_plugins", root=FRAMEWORK_PATH, mode="apply" if args.apply else "plan")

    def on_warning(text: str) -> None:
        if human:
            warn(text)
        else:
            reporter.message("warning", text)

    rendered = render_all(on_warning)
    existing = current_render_targets()
    changes = diff(rendered, existing)
    pending = sum(len(v) for v in changes.values())

    if args.apply:
        for rel in changes["remove"]:
            (PLUGINS_DIR / rel).unlink()
            reporter.mutation("remove", path=PLUGINS_DIR / rel)
        for rel in changes["create"] + changes["update"]:
            target = PLUGINS_DIR / rel
            write_utf8(target, rendered[rel])
            reporter.mutation("write", path=target)
        if human:
            print(f"  [OK]    plugins/: {len(changes['create'])} created, {len(changes['update'])} updated, {len(changes['remove'])} removed")
        else:
            reporter.emit(args.format, summary={"version": version(), **{k: len(v) for k, v in changes.items()}})
        return 0

    if pending:
        for action, items in changes.items():
            for rel in items:
                reporter.message("warning", f"would {action} plugins/{rel}", path=PLUGINS_DIR / rel)
        reporter.set_status("blocked")
    else:
        reporter.set_status("noop")
    if human:
        if pending:
            for action, items in changes.items():
                for rel in items:
                    print(f"  [DIFF]  would {action} plugins/{rel}")
            print("  Re-run with --apply to write plugins/.")
        else:
            print("  [OK]    plugins/ is up to date.")
        return 1 if pending else 0
    reporter.emit(args.format, summary={"version": version(), **{k: len(v) for k, v in changes.items()}})
    return 1 if pending else 0


if __name__ == "__main__":
    sys.exit(main())
